# %% [markdown]
# # Incident review and feedback signals
#
# Reproducible from the warehouse: `python analysis/incident_review.py --db warehouse/observability.duckdb --out analysis/incident_review.md`.
# Synthetic data; simulated SLA and adoption metrics.

# %%
from __future__ import annotations

import argparse
from pathlib import Path

import duckdb


def md_table(rows, cols):
    head = "| " + " | ".join(c for c, _ in cols) + " |\n|" + "---|" * len(cols) + "\n"
    return head + "".join("| " + " | ".join(f(r) for _, f in cols) + " |\n" for r in rows)


def build(con) -> str:
    q = lambda s: con.execute(s).fetchall()
    out = ["# Incident review and feedback signals\n", "Generated by `analysis/incident_review.py` from the gold marts. Synthetic data; demo results.\n"]

    # %% 1. Which missed SLA matters
    rows = q("""select priority_rank, report_name, tier, avg_weekly_viewers, missed, sla_compliance, views_on_stale_data
                from gold.rpt_sla_priority where missed > 0 order by priority_rank limit 8""")
    out.append("## 1. Which missed SLA matters\n\nPriority = average weekly viewers x missed freshness checks, last 90 days.\n")
    out.append(md_table(rows, [("#", lambda r: str(r[0])), ("Report", lambda r: r[1]), ("Tier", lambda r: r[2]), ("Weekly viewers", lambda r: f"{r[3]:.0f}"),
                               ("Missed checks", lambda r: str(r[4])), ("SLA", lambda r: f"{100 * r[5]:.1f}%"), ("Views on stale data", lambda r: f"{r[6]:.0f}")]))
    out.append("\nFive reports read the sales dataset and miss the same nine checks; usage puts the executive scorecard first. "
               "Reports with similar compliance but light usage rank far lower.\n")

    # %% 2. Timeline and root cause
    rows = q("""select h.check_date, h.fresh_at, h.hours_stale, h.views_on_stale_data, s.hours_after_due
                from gold.rpt_report_health h
                left join gold.rpt_sftp_timeliness s on s.retailer_id = 'RT-02' and s.sales_date = h.check_date - interval 1 day
                where h.report_key = 'R-001' and not h.is_fresh and h.check_date between date '2026-10-01' and date '2026-10-31'
                order by 1""")
    out.append("\n## 2. Timeline: Executive Sales Scorecard, October\n\nDue 07:00 UTC with data through the previous day.\n")
    out.append(md_table(rows, [("Check date", lambda r: str(r[0])), ("Current from", lambda r: f"{r[1]:%H:%M}"), ("Hours stale", lambda r: f"{r[2]:.1f}"),
                               ("Views while stale", lambda r: f"{r[3]:.0f}"), ("Retailer RT-02 file, hours after 04:00", lambda r: "–" if r[4] is None else f"{r[4]:.1f}")]))
    out.append("\nEvery missed check follows a late file from the largest retailer: the sales refresh waits for all files. "
               "Remediation options: a partial refresh at 07:00 with a completeness banner, an earlier file cut-off agreed with the retailer, "
               "or an alert to report owners when the file is an hour late.\n")

    # %% 3. Actionable against weak
    a = q("""select app_version, platform, reviews, avg_stars, change_vs_previous, change_vs_previous - 1.96 * se_change, change_vs_previous + 1.96 * se_change, pairing_share
             from gold.rpt_app_versions where signal = 'actionable'""")[0]
    w = q("""select product_id, market, week_start, reviews, avg_stars, baseline_stars, shrunk_stars
             from gold.rpt_ratings_weekly where product_id = 'P-ARC-MINI' and market = 'JP' and signal = 'weak signal'""")[0]
    out.append("\n## 3. An actionable incident against a weak signal\n")
    out.append(f"- **App {a[0]} on {a[1]}:** {a[2]} reviews, {a[3]:.2f} stars, {a[4]:+.2f} against the previous version "
               f"(95% interval {a[5]:+.2f} to {a[6]:+.2f}); {100 * a[7]:.0f}% mention pairing. Actionable.\n")
    out.append(f"- **Arc Speaker Mini, {w[1]}, week of {w[2]}:** {w[3]} reviews averaging {w[4]:.2f} against a baseline of {w[5]:.2f}. "
               f"Shrunk with a prior of 20 reviews it is {w[6]:.2f}. A weak signal: watch, do not escalate.\n")

    # %% 4. Counting
    v = q("select report_name, views_v1, views_v2, share_removed_by_v2 from gold.rpt_metric_versions where share_removed_by_v2 > 0")
    out.append("\n## 4. Counting rules that change the answer\n")
    for r in v:
        out.append(f"- {r[0]}: {r[1]} views under v1, {r[2]} under v2 ({100 * r[3]:.0f}% were a service account).\n")
    c = q("""select sum(views_mapped) filter (where event_date >= date '2026-09-15'), sum(views_naive_filter) filter (where event_date >= date '2026-09-15')
             from gold.rpt_contract_change""")[0]
    out.append(f"- After the API schema change: {c[0]:,} views mapped in staging; a filter on the old activity name finds {c[1]:,}.\n")
    return "\n".join(out)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--db", default="warehouse/observability.duckdb")
    ap.add_argument("--out", default="analysis/incident_review.md")
    a = ap.parse_args()
    with duckdb.connect(a.db, read_only=True) as con:
        Path(a.out).write_text(build(con), encoding="utf-8", newline="\n")
    print("wrote", a.out)


if __name__ == "__main__":
    main()
